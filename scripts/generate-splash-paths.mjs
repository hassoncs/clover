import { writeFileSync } from "fs";
import opentype from "opentype.js";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FONTS_DIR = resolve(__dirname, "../app/assets/fonts");
const OUTPUT_FILE = resolve(__dirname, "../app/components/splashPaths.ts");

const TEXT = "SLOPCADE";

const STYLES = [
	{ family: "Bangers", size: 80, file: "Bangers-Regular.ttf" },
	{ family: "PressStart2P", size: 32, file: "PressStart2P-Regular.ttf" },
	{ family: "Fredoka", size: 72, file: "Fredoka-Bold.ttf" },
	{ family: "Lora", size: 68, file: "Lora-Bold.ttf" },
	{ family: "Bangers", size: 85, file: "Bangers-Regular.ttf" },
	{ family: "PressStart2P", size: 30, file: "PressStart2P-Regular.ttf" },
];

const results = STYLES.map(({ family, size, file }, idx) => {
	const font = opentype.loadSync(resolve(FONTS_DIR, file));

	// Generate path at origin (x=0, y=0 baseline)
	const path = font.getPath(TEXT, 0, 0, size);
	const pathData = path.toPathData(2);

	// Calculate bounding box
	const bb = path.getBoundingBox();
	const width = bb.x2 - bb.x1;
	const height = bb.y2 - bb.y1;

	console.log(
		`[${idx}] ${family} @ ${size}px: ${width.toFixed(1)}x${height.toFixed(1)}, bb: (${bb.x1.toFixed(1)}, ${bb.y1.toFixed(1)}) to (${bb.x2.toFixed(1)}, ${bb.y2.toFixed(1)})`,
	);

	return {
		family,
		size,
		pathData,
		width,
		height,
		// Offset from origin to top-left of bounding box
		offsetX: bb.x1,
		offsetY: bb.y1,
	};
});

const output = `// Auto-generated by scripts/generate-splash-paths.mjs
// Do not edit manually

export interface SplashPathData {
\tfamily: string;
\tsize: number;
\tpathData: string;
\twidth: number;
\theight: number;
\toffsetX: number;
\toffsetY: number;
}

export const SPLASH_PATHS: SplashPathData[] = ${JSON.stringify(results, null, "\t")};
`;

writeFileSync(OUTPUT_FILE, output);
console.log(`\nWrote ${OUTPUT_FILE}`);
