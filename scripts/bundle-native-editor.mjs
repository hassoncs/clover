#!/usr/bin/env node
/**
 * Bundles CodeMirror 6 + setup into a single IIFE for the native WebView editor.
 * Output: app/components/editor/code-editor/native/editor-bundle.generated.ts
 *
 * Run: node scripts/bundle-native-editor.mjs
 */

import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const ENTRY = resolve(ROOT, 'app/components/editor/code-editor/native/editor-entry.js');
const OUTPUT = resolve(ROOT, 'app/components/editor/code-editor/native/editor-bundle.generated.ts');

async function main() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    minify: true,
    write: false,
    target: ['es2020'],
    platform: 'browser',
  });

  const bundledJs = result.outputFiles[0].text;
  const sizeKB = (bundledJs.length / 1024).toFixed(1);

  const tsContent = [
    `// Auto-generated by scripts/bundle-native-editor.mjs`,
    `// Do not edit manually. Re-run: node scripts/bundle-native-editor.mjs`,
    `// Bundle size: ${sizeKB} KB (minified)`,
    ``,
    `export const EDITOR_BUNDLE = ${JSON.stringify(bundledJs)};`,
    ``,
  ].join('\n');

  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, tsContent, 'utf-8');

  console.log(`✓ Bundled CodeMirror editor: ${sizeKB} KB → ${OUTPUT}`);
}

main().catch((err) => {
  console.error('Bundle failed:', err);
  process.exit(1);
});
